# Helpers


def to_number(text: str) -> int | float | str:
    """Convert *text* to ``int``/``float`` only if it round-trips exactly."""
    if re.fullmatch(r"-?\d+", text) and str(int(text)) == text:
        return int(text)
    if re.fullmatch(r"-?\d+\.\d+", text) and repr(float(text)) == text:
        return float(text)
    return text


def _component(text: str, keep_complex_braces: bool) -> int | float | str:
    inner = unbrace_component(text)
    if (
        keep_complex_braces
        and inner != text.strip()
        and re.search(r"[,()\[\]:]", inner)
    ):
        return text.strip()
    return to_number(inner)


def _cartesian(coord: Coord, keep_complex_braces: bool) -> tuple[Any, ...]:
    if coord.prefix:
        raise Unsupported("relative coordinate", f"{coord.prefix}({coord.inner})")
    kind = coord.kind
    if kind != "cartesian":
        raise Unsupported(f"{kind} coordinate", coord.inner)
    return tuple(_component(p, keep_complex_braces) for p in coord.components)


def split_options(
    options: list[Option] | tuple[Option, ...],
    reserved: frozenset[str] = frozenset(),
    structured: bool = True,
) -> tuple[list[str], dict[str, Any]]:
    """Split parsed options into ``options=[...]`` and keyword arguments.

    Keyword arguments are only used when rendering them keeps the original
    order (all flags first, then unique ``key=value`` pairs whose keys map
    cleanly to Python identifiers-with-spaces). Otherwise every option is
    returned verbatim as a flag string, which always renders identically.
    """
    raw = [o.raw for o in options]
    if not structured:
        return raw, {}
    flags: list[str] = []
    kwargs: dict[str, Any] = {}
    seen_key = False
    for option in options:
        if option.key is None:
            if seen_key:
                return raw, {}
            flags.append(option.raw)
            continue
        seen_key = True
        key = option.key.replace(" ", "_")
        if (
            "_" in option.key
            or key in reserved
            or key in kwargs
            or not re.fullmatch(r"[A-Za-z][A-Za-z0-9_]*", key)
        ):
            return raw, {}
        kwargs[key] = option.value or ""
    return flags, kwargs


class _Sink:
    """Where mapped objects go: a figure layer or a Scope/Loop body."""

    def __init__(
        self,
        figure: TikzFigure,
        container: Scope | Loop | None = None,
        layer: int = 0,
    ) -> None:
        self.figure = figure
        self.container = container
        self.layer = layer

    @property
    def top_level(self) -> bool:
        return self.container is None

    def resolve(self, label: str) -> Node | Coordinate:
        if self.container is not None:
            return self.container.get_node(label)
        return self.figure.layers.get_node(label)

    def add(self, item: Any) -> None:
        if self.container is not None:
            self.container.items.append(item)
        else:
            self.figure.layers.add_item(item=item, layer=self.layer)

    def add_node(self, node: Node) -> None:
        if self.container is not None:
            self.container.add_node(node)
        else:
            self.figure.add_node(node)


def _rendered_statement(item: Any) -> Statement:
    statements = [s for s in split_statements(item.to_tikz()) if s.kind != "comment"]
    if len(statements) != 1:
        raise Unsupported("lossy mapping", "rendered to multiple statements")
    return statements[0]


